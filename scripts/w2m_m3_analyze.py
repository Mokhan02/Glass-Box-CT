"""W2-M M3 analysis (results/w2_mech/PREREG.md, applied as written). Per lesion D = LEAK(edit) - LEAK(control), paired; arm statistic = mean D with a case-level bootstrap (1000 resamples, seed 0, 95% percentile CI).
SUPPORTED iff Arm A has CI lower > 0 and point >= 0.10 AND Arm B has CI upper < 0 and point <= -0.10. PARTIAL if exactly one arm meets its condition. NOT SUPPORTED if neither meets its condition, both point estimates are zero or in the wrong direction,
and each arm has >= 10 lesions. INCONCLUSIVE otherwise, including any arm with fewer than 10 lesions. Secondary: edit-minus-control change in Dice and coverage and the failure-mode shifts.
EXPLORATORY: paired projection change (edit minus unedited, kidney-native probe at the mid-encoder, per-fold probe applied to held-out patients) and its Spearman correlation with the Dice change (edit minus unedited).
Usage: python scripts/w2m_m3_analyze.py <w2m_m3_runs.csv> <outdir>"""
import csv
import json
import sys

import numpy as np
from scipy.stats import spearmanr

B, SEED = 1000, 0


def boot_mean(v, cases, rng):
    v = np.asarray(v, float); uc = sorted(set(cases)); idx = {c: np.flatnonzero(np.array(cases) == c) for c in uc}
    s = np.array([[np.nansum(v[idx[c]]), np.sum(~np.isnan(v[idx[c]]))] for c in uc]); ok = s[:, 1] > 0
    pt = s[:, 0].sum() / s[:, 1].sum(); r = rng.integers(0, len(uc), (B, len(uc))); den = s[r, 1].sum(1); d = (s[r, 0].sum(1) / np.where(den == 0, np.nan, den)); d = d[np.isfinite(d)]
    return {"mean": float(pt), "lo": float(np.percentile(d, 2.5)), "hi": float(np.percentile(d, 97.5)), "n": int((~np.isnan(v)).sum()), "n_cases": int(ok.sum())}


def verdict(A, Bm):
    a_ok = A["lo"] > 0 and A["mean"] >= 0.10; b_ok = Bm["hi"] < 0 and Bm["mean"] <= -0.10
    if A["n"] < 10 or Bm["n"] < 10:
        return "INCONCLUSIVE (an arm has fewer than 10 lesions)", a_ok, b_ok
    if a_ok and b_ok:
        return "SUPPORTED", a_ok, b_ok
    if a_ok or b_ok:
        return "PARTIAL", a_ok, b_ok
    return ("NOT SUPPORTED" if (A["mean"] <= 0 and Bm["mean"] >= 0) else "INCONCLUSIVE"), a_ok, b_ok


def main(runs_csv, out):
    rng = np.random.default_rng(SEED); rows = list(csv.DictReader(open(runs_csv))); R = {}
    for arm in ("A", "B"):
        g = {(r["case"], int(r["rank"]), r["condition"]): r for r in rows if r["arm"] == arm}; keys = sorted({k[:2] for k in g}); cases = [k[0] for k in keys]
        leak = lambda k, c: float(g[(k[0], k[1], c)]["mode"] == "LEAK")
        D = [leak(k, "edit") - leak(k, "control") for k in keys]
        f = lambda key, c: np.array([float(g[(k[0], k[1], c)][key]) for k in keys])
        R[arm] = {"n_lesions": len(keys), "n_cases": len(set(cases)), "leak_rate": {c: float(np.mean([leak(k, c) for k in keys])) for c in ("baseline", "control", "edit")}, "D_leak_edit_minus_control": boot_mean(D, cases, rng),
                  "dice_edit_minus_control": boot_mean(f("dice_full", "edit") - f("dice_full", "control"), cases, rng), "coverage_edit_minus_control": boot_mean(f("coverage", "edit") - f("coverage", "control"), cases, rng),
                  "flagged_edits": int(sum(g[(k[0], k[1], c)]["flagged"] == "True" for k in keys for c in ("edit", "control"))),
                  "failure_modes": {c: {m: float(np.mean([g[(k[0], k[1], c)]["mode"] == m for k in keys])) for m in ("LEAK", "UNDER", "OK")} for c in ("baseline", "control", "edit")}}
        dproj = f("projection_native_probe", "edit") - f("projection_native_probe", "baseline"); ddice = f("dice_full", "edit") - f("dice_full", "baseline"); ok = ~np.isnan(dproj)
        rho = spearmanr(dproj[ok], ddice[ok])[0] if ok.sum() > 3 else float("nan"); draws = []
        idx = {c: np.flatnonzero(np.array(cases) == c) for c in sorted(set(cases))}; uc = sorted(idx)
        for _ in range(B):
            pick = np.concatenate([idx[uc[i]] for i in rng.integers(0, len(uc), len(uc))]); m = ok[pick]
            if m.sum() > 3:
                draws.append(spearmanr(dproj[pick][m], ddice[pick][m])[0])
        R[arm]["exploratory_projection"] = {"projection_change_edit_minus_unedited": boot_mean(dproj, cases, rng), "spearman_with_dice_change": {"rho": float(rho), "lo": float(np.nanpercentile(draws, 2.5)), "hi": float(np.nanpercentile(draws, 97.5))}, "lesions_with_tokens": int(ok.sum())}
    v, a_ok, b_ok = verdict(R["A"]["D_leak_edit_minus_control"], R["B"]["D_leak_edit_minus_control"]); R["verdict"] = {"verdict": v, "arm_A_meets": bool(a_ok), "arm_B_meets": bool(b_ok)}
    json.dump(R, open(f"{out}/m3_results.json", "w"), indent=1)
    f_ = lambda m, s=1.0: f"{m['mean'] * s:+.3f} [{m['lo'] * s:+.3f}, {m['hi'] * s:+.3f}]"
    L = ["# W2-M M3 results (generated by scripts/w2m_m3_analyze.py, applied as written)", "", "C4KC-KiTS: possibly seen in training (images, via AbdomenCT-1K). Kidney arm = label 133 + point label 1; HU edits change the lesion mean only.", "",
         f"## Verdict (primary: change in LEAK rate, edit minus sign-keeping control): **{R['verdict']['verdict']}**",
         f"- Arm A (dark to bright; {R['A']['n_lesions']} lesions, {R['A']['n_cases']} cases): D = {f_(R['A']['D_leak_edit_minus_control'], 100)} pts (needs CI lower > 0 and point >= +10): meets {a_ok}",
         f"- Arm B (bright to dark; {R['B']['n_lesions']} lesions, {R['B']['n_cases']} cases): D = {f_(R['B']['D_leak_edit_minus_control'], 100)} pts (needs CI upper < 0 and point <= -10): meets {b_ok}", "",
         "## LEAK / UNDER / OK rates", "| arm | condition | LEAK | UNDER | OK |", "|---|---|---|---|---|"]
    for arm in ("A", "B"):
        for c in ("baseline", "control", "edit"):
            fm = R[arm]["failure_modes"][c]; L.append(f"| {arm} | {c} | {100 * fm['LEAK']:.0f}% | {100 * fm['UNDER']:.0f}% | {100 * fm['OK']:.0f}% |")
    L += ["", "## Secondary: edit minus sign-keeping control", "| arm | Dice change | coverage change | flagged edits (> 5 HU off) |", "|---|---|---|---|"] + [f"| {a} | {f_(R[a]['dice_edit_minus_control'])} | {f_(R[a]['coverage_edit_minus_control'])} | {R[a]['flagged_edits']} |" for a in ("A", "B")]
    L += ["", "## EXPLORATORY: projection on the kidney-native tumour direction (mid-encoder), edit minus unedited", "| arm | projection change | Spearman with Dice change | lesions with tokens |", "|---|---|---|---|"]
    for a in ("A", "B"):
        e = R[a]["exploratory_projection"]; s = e["spearman_with_dice_change"]; L.append(f"| {a} | {f_(e['projection_change_edit_minus_unedited'])} | {s['rho']:+.2f} [{s['lo']:+.2f}, {s['hi']:+.2f}] | {e['lesions_with_tokens']} |")
    open(f"{out}/m3_results.md", "w").write("\n".join(L) + "\n"); print("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
